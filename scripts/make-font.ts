/** Acentos: base + marca encima (en minúsculas cabe en la fila 0; en mayúsculas, 2 filas por encima). */
const ACCENTS: Record<string, [string, 'acute' | 'diaeresis' | 'tilde']> = {
  á: ['a', 'acute'], é: ['e', 'acute'], í: ['i', 'acute'], ó: ['o', 'acute'], ú: ['u', 'acute'],
  ü: ['u', 'diaeresis'], ñ: ['n', 'tilde'],
  Á: ['A', 'acute'], É: ['E', 'acute'], Í: ['I', 'acute'], Ó: ['O', 'acute'], Ú: ['U', 'acute'],
  Ü: ['U', 'diaeresis'], Ñ: ['N', 'tilde'],
};
G.U = ['#...#', '#...#', '#...#', '#...#', '#...#', '#...#', '.###.'];

function marks(kind: 'acute' | 'diaeresis' | 'tilde', w: number): [number, number][] {
  const mid = Math.floor(w / 2);
  if (kind === 'acute') return [[mid + 1, 0], [mid, 1]].map(([x, y]) => [Math.min(w - 1, x!), y!] as [number, number]);
  if (kind === 'diaeresis') return [[Math.max(0, mid - 1), 1], [Math.min(w - 1, mid + 1), 1]];
  return [[0, 1], [1, 0], [2, 1], [3, 0]].filter(([x]) => x! < w) as [number, number][];
}

function pixels(ch: string): { px: [number, number][]; w: number } {
  const acc = ACCENTS[ch];
  const base = acc ? G[acc[0]]! : G[ch]!;
  const w = base[0]!.length;
  const px: [number, number][] = [];
  base.forEach((row, y) => [...row].forEach((c, x) => c === '#' && px.push([x, y])));
  if (acc) {
    const upper = acc[0] === acc[0].toUpperCase();
    // Mayúsculas: marca en las filas −2 y −1. Minúsculas: en las filas 0 y 1, sobre la x (la i pierde su punto).
    if (acc[0] === 'i') for (let i = px.length - 1; i >= 0; i--) if (px[i]![1] === 0) px.splice(i, 1);
    for (const [x, y] of marks(acc[1], w)) px.push([x, upper ? y - 2 : y]);
  }
  return { px, w };
}

function glyph(ch: string): opentype.Glyph {
  const { px, w } = pixels(ch);
  const path = new opentype.Path();
  for (const [x, y] of px) {
    // Fila y (0 = arriba de la mayúscula) → de (6 − y)·U a (7 − y)·U sobre la línea base.
    const x0 = x * U;
    const y0 = (6 - y) * U;
    path.moveTo(x0, y0);
    path.lineTo(x0 + U, y0);
    path.lineTo(x0 + U, y0 + U);
    path.lineTo(x0, y0 + U);
    path.close();
  }
  return new opentype.Glyph({ name: `u${ch.codePointAt(0)!.toString(16)}`, unicode: ch.codePointAt(0)!, advanceWidth: (w + 1) * U, path });
}

